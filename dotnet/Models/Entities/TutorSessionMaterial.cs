using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace Backend.Models.Entities;

/// <summary>
/// Lot 9.6 (suivi 17.5, partie génération) : support de séance généré par
/// WinAI à partir des sujets saisis à la réservation, pour UNE séance
/// (<see cref="TutorBooking"/>, unique ou issue d'un engagement mensuel,
/// individuelle ou de groupe). Un support par séance.
/// <para>
/// Versionné : <see cref="ContentJson"/> est la copie de travail du tuteur
/// (brouillon), régénérée ou modifiée autant qu'il veut ;
/// <see cref="SharedContentJson"/> est la version partagée, seule visible des
/// participants et du payeur. Partager recopie la copie de travail et fixe
/// <see cref="SharedVersion"/>. Le contenu reste affiché dans l'application :
/// ce n'est ni une épreuve ni un livre du catalogue, et aucun fichier n'en est
/// produit (décision 18.21).
/// </para>
/// Schéma : Migrations/SQL_TutorSessionMaterials.sql.
/// </summary>
public class TutorSessionMaterial
{
    public int Id { get; set; }

    public int TutorBookingId { get; set; }

    /// <summary>Tuteur auteur (compte débité des tokens de génération).</summary>
    public int TutorUserId { get; set; }

    /// <summary><see cref="TutorSessionMaterialStatuses"/> : draft (jamais partagé) ou shared (partagé au moins une fois).</summary>
    [MaxLength(20)]
    public string Status { get; set; } = TutorSessionMaterialStatuses.Draft;

    /// <summary>Numéro de la copie de travail, incrémenté à chaque génération ou modification enregistrée.</summary>
    public int Version { get; set; } = 1;

    /// <summary>Version partagée (null tant que rien n'est partagé).</summary>
    public int? SharedVersion { get; set; }

    [MaxLength(200)]
    public string Title { get; set; } = "";

    /// <summary>Copie de travail (JSON <c>TutorSessionMaterialContent</c>) : cours, quiz, exercices.</summary>
    public string ContentJson { get; set; } = "{}";

    /// <summary>Version partagée, figée au partage (JSON du même format).</summary>
    public string? SharedContentJson { get; set; }

    /// <summary>generated | edited : origine de la dernière modification de la copie de travail.</summary>
    [MaxLength(20)]
    public string LastChange { get; set; } = "generated";

    /// <summary>Nombre de générations WinAI (première comprise).</summary>
    public int GenerationCount { get; set; }

    /// <summary>Générée automatiquement à l'acceptation de la séance (réglage du tuteur).</summary>
    public bool AutoGenerated { get; set; }

    public DateTime? GeneratedAt { get; set; }
    public DateTime? SharedAt { get; set; }
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    public DateTime? UpdatedAt { get; set; }

    [ForeignKey(nameof(TutorBookingId))]
    public TutorBooking? TutorBooking { get; set; }

    public ICollection<TutorSessionMaterialResult> Results { get; set; } = new List<TutorSessionMaterialResult>();
}

/// <summary>
/// Réponses d'un élève participant au quiz et aux exercices d'un support
/// partagé (lot 9.6). Une ligne par élève et par support ; un nouveau partage
/// (version supérieure) permet de refaire le quiz.
/// </summary>
public class TutorSessionMaterialResult
{
    public int Id { get; set; }
    public int TutorSessionMaterialId { get; set; }
    public int StudentUserId { get; set; }

    /// <summary>Version partagée à laquelle l'élève a répondu.</summary>
    public int MaterialVersion { get; set; }

    /// <summary>Réponses au quiz : { "q1": "b", ... }.</summary>
    public string QuizAnswersJson { get; set; } = "{}";

    public int QuizScore { get; set; }
    public int QuizTotal { get; set; }

    /// <summary>Réponses rédigées aux exercices : { "e1": "...", ... }.</summary>
    public string ExerciseAnswersJson { get; set; } = "{}";

    public DateTime SubmittedAt { get; set; } = DateTime.UtcNow;

    /// <summary>Le tuteur a consulté ce résultat (remontée au tuteur).</summary>
    public DateTime? SeenByTutorAt { get; set; }

    [ForeignKey(nameof(TutorSessionMaterialId))]
    public TutorSessionMaterial? Material { get; set; }

    [ForeignKey(nameof(StudentUserId))]
    public User? Student { get; set; }
}

public static class TutorSessionMaterialStatuses
{
    public const string Draft = "draft";
    public const string Shared = "shared";
}
